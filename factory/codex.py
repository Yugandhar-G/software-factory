#!/usr/bin/env python3
"""Generate the Codex form of this plugin for one project.

  factory codex install <project> [--force]

Codex does not load Claude Code plugins, so this writes, from the same sources:
  <project>/.agents/skills/<name>/   every skill, ${CLAUDE_PLUGIN_ROOT} made absolute
  <project>/.codex/agents/<role>.toml  every agent (name, description, instructions)
  <project>/.codex/hooks.json          the work-loss hook, pointing at this checkout
Every generated file is recorded with its hash in .codex/factory-generated.json;
on a rerun a file is replaced only if it still matches what was generated (or
carries the marker), so hand edits and unrelated files are never overwritten
unless --force is given. Rerun after updating the plugin.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

PLUGIN = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PLUGIN))
from factory.harness.agents import load as load_agents  # noqa: E402

MARKER = 'generated by the factory plugin'


def substitute(text):
    return text.replace('${CLAUDE_PLUGIN_ROOT}', str(PLUGIN))


def toml_string(text):
    """A TOML multi-line basic string: backslashes, quotes and control characters escaped."""
    escaped = text.replace('\\', '\\\\').replace('"', '\\"')
    escaped = ''.join(c if c in '\n\t' or ord(c) >= 0x20 and ord(c) != 0x7f else f'\\u{ord(c):04x}'
                      for c in escaped)
    return f'"""\n{escaped}"""'


def agent_toml(agent):
    return (f'# {MARKER}; edit agents/{agent.name}.md in the plugin instead\n'
            f'name = {json.dumps(agent.name, ensure_ascii=False)}\n'
            f'description = {json.dumps(agent.description, ensure_ascii=False)}\n'
            f'developer_instructions = {toml_string(agent.instructions + chr(10))}\n')


def hooks_json():
    guard = PLUGIN / 'factory' / 'scripts' / 'destructive_guard.py'
    return json.dumps({'_comment': MARKER, 'hooks': {'PreToolUse': [{'matcher': 'Bash', 'hooks': [
        {'type': 'command', 'command': f'python3 "{guard}"'}]}]}}, indent=2) + '\n'


def digest(data):
    return hashlib.sha256(data).hexdigest()


class Writer:
    """Writes generated files, replacing only files it generated and nobody has edited since."""

    def __init__(self, project, force):
        self.project, self.force, self.written, self.skipped = project, force, [], []
        self.ledger_path = project / '.codex' / 'factory-generated.json'
        self.ledger = json.loads(self.ledger_path.read_text()) if self.ledger_path.is_file() else {}

    def write(self, path, data):
        data = data.encode() if isinstance(data, str) else data
        key = path.relative_to(self.project).as_posix()
        if path.exists():
            current = path.read_bytes()
            if current == data:
                self.ledger[key] = digest(data)
                return
            ours = self.ledger.get(key) == digest(current) or MARKER.encode() in current
            if not ours and not self.force:
                self.skipped.append(str(path))
                return
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        self.ledger[key] = digest(data)
        self.written.append(str(path))

    def save(self):
        self.ledger_path.parent.mkdir(parents=True, exist_ok=True)
        self.ledger_path.write_text(json.dumps(dict(sorted(self.ledger.items())), indent=2) + '\n')


def install(project, force=False):
    project = Path(project).resolve()
    out = Writer(project, force)
    for skill in sorted((PLUGIN / 'skills').iterdir()):
        if not skill.is_dir():
            continue
        for source in sorted(p for p in skill.rglob('*') if p.is_file() and '__pycache__' not in p.parts):
            target = project / '.agents' / 'skills' / skill.name / source.relative_to(skill)
            if source.name == 'SKILL.md':
                text = substitute(source.read_text())
                head, sep, body = text.partition('\n---\n')  # marker after the frontmatter
                out.write(target, f'{head}{sep}<!-- {MARKER} -->\n{body}' if sep else text)
            else:
                out.write(target, source.read_bytes())
                if source.stat().st_mode & 0o111 and str(target) in out.written:
                    target.chmod(target.stat().st_mode | 0o111)
    for agent in load_agents().values():
        out.write(project / '.codex' / 'agents' / f'{agent.name}.toml', agent_toml(agent))
    out.write(project / '.codex' / 'hooks.json', hooks_json())
    out.save()
    return out


def main():
    parser = argparse.ArgumentParser(prog='factory codex', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='command', required=True)
    command = sub.add_parser('install')
    command.add_argument('project', type=Path)
    command.add_argument('--force', action='store_true', help='overwrite files the plugin did not generate')
    args = parser.parse_args()
    out = install(args.project, args.force)
    print(json.dumps(dict(written=len(out.written), skipped=out.skipped), indent=2))
    if out.skipped:
        parser.exit(1, 'Some files exist and were not generated by the plugin; review them, then rerun with --force.\n')


if __name__ == '__main__':
    main()
