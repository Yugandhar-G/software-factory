#!/usr/bin/env python3
"""Keep a project's AGENTS.md and factory profile in step with the plugin.

  factory onboard [project] [--write] [--check] [--force]

Two things are generated, everything else in the project is left alone:

- The workflow block in AGENTS.md, between the BEGIN and END markers: the factory's
  steps, the skill behind each step, the agent rules, and a table of the plugin's
  skills, minus the ones `.factory/config.json` "skills_off" rules out (each with
  its reason). A missing block goes before the first `## ` section; a missing
  AGENTS.md is created with only a title and the block.
- `.factory/profile.md`, copied from the "## Factory profile" section of AGENTS.md
  (its `### All roles` and `### <role>` subsections), so a project writes its rules
  once, where people read them. A profile without the generated marker is a
  person's file and is replaced only with --force.

Without --write nothing is written; the command lists what would change. --check
exits 1 when anything would change, for CI and pre-commit. Drafting the project's
own facts (commands, invariants, protected paths, architecture) is the onboarder
agent's job, and a person approves it; this script never writes those.
"""
import argparse
from dataclasses import dataclass, field
from pathlib import Path
import re
import sys

PLUGIN = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PLUGIN))
from factory.scripts import home  # noqa: E402

BEGIN = '<!-- factory:workflow begin; generated by the factory plugin, run `factory onboard --write` to refresh -->'
END = '<!-- factory:workflow end -->'
PROFILE_MARKER = '<!-- generated by the factory plugin from AGENTS.md "## Factory profile"; edit AGENTS.md -->'
PROFILE_HEADING = 'factory profile'
TEMPLATE = PLUGIN / 'templates' / 'agents-workflow.md'
AGENTS = 'AGENTS.md'
DESCRIPTION_LIMIT = 150

# Which step each skill belongs to; a skill not listed here still appears in the table.
STEP_SKILLS = {
    'isolate': ('new-feature',),
    'build': ('code-structure',),
    'prove': ('evidence-driven-testing', 'before-and-after'),
    'review': ('review-loop',),
    'ship_prose': ('unslop',),
    'ship_review': ('greploop', 'greploop-apps'),
}


class OnboardError(Exception):
    """The project's files are in a state onboard will not guess its way through."""


@dataclass
class Plan:
    changed: list = field(default_factory=list)
    skipped: list = field(default_factory=list)
    notes: list = field(default_factory=list)


def skill_descriptions():
    """{skill: first sentence of its description}, from each SKILL.md frontmatter."""
    found = {}
    for path in sorted((PLUGIN / 'skills').glob('*/SKILL.md')):
        head = path.read_text().split('\n---\n', 1)[0]
        match = re.search(r'^description:[ \t]*(.*)$((?:\n[ \t]+.*)*)', head, re.M)
        text = ''
        if match:
            first, rest = match.group(1).strip(), match.group(2)
            text = ' '.join(line.strip() for line in rest.splitlines()) if first in {'>', '|', '>-', '|-'} \
                else ' '.join([first, *(line.strip() for line in rest.splitlines())])
        # Upstream descriptions may carry dashes; many projects ban them in docs, so use commas.
        text = re.sub(r'\s*[\u2014\u2013]\s*', ', ', text)
        sentence = re.split(r'(?<=[.!?])\s', text.strip(), maxsplit=1)[0]
        if len(sentence) > DESCRIPTION_LIMIT:
            sentence = sentence[:DESCRIPTION_LIMIT].rsplit(' ', 1)[0] + '...'
        found[path.parent.name] = sentence.replace('|', '\\|')
    return found


def skills_off(project):
    """{skill: reason} the project rules out; an unknown skill name is an error, not a no-op."""
    value = home.config(project).get('skills_off', {})
    if not isinstance(value, dict) or not all(isinstance(r, str) and r.strip() for r in value.values()):
        raise OnboardError('.factory/config.json "skills_off" must map skill names to a reason')
    unknown = sorted(set(value) - set(skill_descriptions()))
    if unknown:
        raise OnboardError(f'"skills_off" names skills the plugin does not have: {", ".join(unknown)}')
    return value


def named(skills, off):
    on = [f'`{s}`' for s in skills if s not in off]
    return ' and '.join(on)


def workflow_block(project):
    cfg = home.config(project)
    off = skills_off(project)
    descriptions = skill_descriptions()
    isolate = named(STEP_SKILLS['isolate'], off) or 'by hand'
    build = named(STEP_SKILLS['build'], off)
    prove = named(STEP_SKILLS['prove'], off) or 'the project checks'
    review = named(STEP_SKILLS['review'], off) or 'the reviewer roles'
    ship = ''
    if named(STEP_SKILLS['ship_prose'], off):
        ship += f'; the title, body and commit messages through {named(STEP_SKILLS["ship_prose"], off)}'
    if named(STEP_SKILLS['ship_review'], off):
        ship += (f'; when an external review service is configured, {named(STEP_SKILLS["ship_review"], off)}'
                 ' with its real feedback')
    rows = '\n'.join(f'| `{name}` | {text} |' for name, text in descriptions.items() if name not in off)
    off_lines = ''
    if off:
        off_lines = '\nNot used in this repository:\n\n' + '\n'.join(
            f'- `{name}`: {reason.strip()}' for name, reason in sorted(off.items()))
    text = TEMPLATE.read_text()
    for key, value in {
        'isolate': isolate, 'build_skill': f', with {build} when logic repeats' if build else '',
        'prove': prove, 'review': review, 'ship': ship, 'skills': rows, 'skills_off': off_lines,
        'branch_prefix': cfg['branch_prefix'], 'worktrees_dir': cfg['worktrees_dir'].rstrip('/'),
    }.items():
        text = text.replace('{{' + key + '}}', value)
    return f'{BEGIN}\n{text.strip()}\n{END}'


def with_block(text, block):
    """AGENTS.md text with the block inserted or replaced; refuses malformed markers."""
    begins, ends = text.count(BEGIN), text.count(END)
    if begins == ends == 0:
        match = re.search(r'^## ', text, re.M)
        if match is None:
            return text.rstrip('\n') + '\n\n' + block + '\n'
        return text[:match.start()] + block + '\n\n' + text[match.start():]
    if begins != 1 or ends != 1 or text.index(BEGIN) > text.index(END):
        raise OnboardError('AGENTS.md has a broken factory:workflow block (markers missing, repeated or '
                           'out of order); fix the markers by hand, then rerun')
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + block + text[stop:]


def profile_from(agents_text):
    """The generated profile, or None when AGENTS.md has no "## Factory profile" section."""
    lines, inside, seen, fenced = [], False, False, False
    for line in agents_text.splitlines():
        if line.lstrip().startswith('```'):
            fenced = not fenced
        heading = None if fenced else re.fullmatch(r'(#{1,6}) +(.+?)\s*', line)
        if heading and len(heading.group(1)) <= 2:
            inside = len(heading.group(1)) == 2 and heading.group(2).strip().lower() == PROFILE_HEADING
            seen = seen or inside
            continue
        if inside:
            lines.append(line)
    if not seen:
        return None
    body, roles = [], []
    for line in lines:
        heading = None if line.lstrip().startswith('```') else re.fullmatch(r'### +(.+?)\s*', line)
        if heading:
            roles.append(heading.group(1).strip().lower())
            line = f'## {heading.group(1).strip()}'
        body.append(line)
    unknown = [r for r in roles if r not in {'all roles', *home.ROLES}]
    if unknown:
        raise OnboardError(f'"## Factory profile" has subsections that match no role: {", ".join(unknown)}; '
                           f'use "All roles" or one of {", ".join(home.ROLES)}')
    return (f'{PROFILE_MARKER}\n# Factory profile\n\nGenerated from AGENTS.md. Change the rules there, then run '
            '`factory onboard --write`.\n\n' + '\n'.join(body).strip() + '\n')


def run(project, *, write=False, force=False):
    """Compute the generated files and, with write, save them. Returns what changed."""
    project = Path(project).resolve()
    plan = Plan()
    agents_path = project / AGENTS
    current = agents_path.read_text() if agents_path.is_file() else ''
    updated = with_block(current or '# AGENTS.md\n', workflow_block(project))
    if updated != current:
        plan.changed.append(AGENTS)
        if write:
            agents_path.write_text(updated)
    profile = profile_from(updated)
    target = home.profile_path(project)
    key = target.relative_to(project).as_posix()
    if profile is None:
        plan.notes.append('AGENTS.md has no "## Factory profile" section; the profile was not generated')
        return plan
    existing = target.read_text() if target.is_file() else None
    if existing == profile:
        return plan
    if existing is not None and PROFILE_MARKER not in existing and not force:
        plan.skipped.append(key)
        plan.notes.append(f'{key} was written by a person; rerun with --force to replace it from AGENTS.md')
        return plan
    plan.changed.append(key)
    if write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(profile)
    return plan


def main():
    parser = argparse.ArgumentParser(prog='factory onboard', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('project', nargs='?', type=Path, default=None)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='save the generated files')
    mode.add_argument('--check', action='store_true', help='exit 1 when anything would change')
    parser.add_argument('--force', action='store_true', help='replace a profile a person wrote')
    args = parser.parse_args()
    project = home.project_root(args.project) if args.project is None else args.project
    try:
        plan = run(project, write=args.write, force=args.force)
    except (OnboardError, ValueError) as exc:
        parser.exit(2, f'factory onboard: {exc}\n')
    verb = 'Updated' if args.write else 'Would update'
    for name in plan.changed:
        print(f'{verb} {name}.')
    for note in plan.notes:
        print(note)
    if not plan.changed:
        print('Everything the factory generates is up to date.')
    if args.check and plan.changed:
        sys.exit(1)


if __name__ == '__main__':
    main()
